import { defineEventHandler, readBody } from 'h3'

export default defineEventHandler(async (event) => {
  const body = await readBody(event)
  const config = useRuntimeConfig()
  
  // Используем IP шлюза Docker для обращения к хосту (Ollama)
  const OLLAMA_URL = 'http://172.19.0.1:11434/api/generate'
  
  try {
    const domain = body.domain.replace('www.', '')
    
    // 1. Получаем конфиг дилера
    const dealerData = await $fetch(`${config.public.apiBase}/v1/tenant/config`, {
      headers: { 'host': domain, 'x-forwarded-host': domain }
    }) as any

    if (!dealerData) {
      return { content: 'Извините, не удалось загрузить данные дилера.' }
    }

    // 2. Формируем описание видов сеток (базовые знания)
    const meshTypes = `
    - Стандартная: Самый доступный вариант, защита от мух и комаров.
    - Антикошка (Pet Screen): Усиленное полотно, выдерживает когти животных.
    - Антипыль (Poll-Tex): Мелкая ячейка, задерживает пыльцу и аллергены.
    - Ультравью (Ultraview): Максимально прозрачная нить, пропускает больше света и воздуха.
    - Вставная VSN: Устанавливается изнутри без сверления рамы.
    `

    // 3. Актуальные цены (только для справки ИИ, не выводить списком сразу)
    // Используем реалистичные цены "от" для дилера
    const pricesInfo = `
    - Стандарт: от 750 руб.
    - Антикошка: от 1800 руб.
    - Антипыль: от 2200 руб.
    - Ультравью: от 2000 руб.
    `
    
    // 4. Формируем системный промпт
    const systemPrompt = `
    Ты — живой и дружелюбный консультант компании "${dealerData.dealer_name || 'Сетки 21'}".
    Твоя задача: помочь клиенту выбрать сетку, общаясь как человек, а не как робот.
    
    ИНФОРМАЦИЯ О ТЕБЕ:
    - Город: ${dealerData.city}
    - Телефон: ${dealerData.phone}
    - Адрес: ${dealerData.address || 'указан на сайте'}
    
    ВИДЫ СЕТОК:
    ${meshTypes}
    
    ЦЕНЫ (для справки, называй только если спросят):
    ${pricesInfo}
    
    ПРАВИЛА ОБЩЕНИЯ:
    1. НЕ выводи список цен сразу. Сначала узнай, что важно клиенту (защита от кошек, аллергия на пыль или просто защита от комаров).
    2. Общайся кратко и по делу. Не пиши огромные тексты.
    3. Если клиент не знает что выбрать, кратко опиши разницу между Стандартом, Антикошкой и Антипылью.
    4. В конце диалога или если клиент готов заказать, предложи оставить телефон для связи с менеджером или воспользоваться калькулятором на сайте.
    5. Называй цены только "ОТ ... рублей", уточняя что точный расчет делает калькулятор или мастер.
    6. НЕ придумывай "Модель 1", "Модель 2". Используй названия: Стандартная, Антикошка, Антипыль и т.д.
    `

    // 5. Запрос к Ollama
    const response = await $fetch(OLLAMA_URL, {
      method: 'POST',
      body: {
        model: 'qwen2.5:0.5b',
        prompt: body.message,
        system: systemPrompt,
        stream: false,
        options: {
          temperature: 0.4, // Снижаем температуру для большей стабильности
          num_predict: 250
        }
      }
    }) as any

    return { content: response.response || 'Извините, я временно не могу ответить.' }
  } catch (e) {
    console.error('AI Chat Proxy Error:', e)
    return { content: 'Произошла ошибка при обращении к ИИ. Пожалуйста, попробуйте позже.' }
  }
})
